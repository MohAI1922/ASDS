"""Automated LaTeX, Markdown, and JSON Scientific Monograph & Provenance Exporters."""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import sympy as sp


def export_discovery_json(result_dict: dict[str, Any], output_path: str | Path) -> Path:
    p = Path(output_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(json.dumps(result_dict, indent=2, default=str), encoding="utf-8")
    return p


def export_markdown_report(result_dict: dict[str, Any], output_path: str | Path | None = None) -> Path | str:
    """Generate a publication-structured Markdown scientific discovery report."""
    lines = [
        f"# ASDS-OMEGA v2.0 (VECSD) — Autonomous Scientific Discovery Report",
        "",
        f"- **System:** `{result_dict['dataset_name']}` ({result_dict['domain']})",
        f"- **Provenance Config Hash:** `{result_dict['config_hash']}` | **Seed:** `{result_dict['seed']}` | **Runtime:** `{result_dict['runtime_sec']:.3f}s`",
        f"- **Estimated Channel Noise (Wavelet-MAD):** `{result_dict['estimated_noise_stds']}`",
        "",
        "## 1. Discovered Governing Equations",
        "",
        "| State Derivative | Discovered Symbolic Law | Weak $R^2$ | Complexity | MDL | Source |",
        "|---|---|---:|---:|---:|---|",
    ]
    for eq in result_dict["discovered_equations"]:
        lines.append(
            f"| `d({eq['target_var']})/dt` | `{eq['expr_str']}` | {eq['weak_r2']:.4f} | {eq['complexity']} | {eq['mdl_score']:.2f} | `{eq['source']}` |"
        )

    lines.extend(["", "## 2. Direct Differential Causal Graph (`VIFC`)", ""])
    c_metrics = result_dict["causal"].get("metrics", {})
    if c_metrics:
        lines.append(
            f"- **Differential SHD:** `{c_metrics.get('shd', 0):.0f}` | **Precision:** `{c_metrics.get('precision', 0):.3f}` | **Recall:** `{c_metrics.get('recall', 0):.3f}` | **F1:** `{c_metrics.get('f1', 0):.3f}`"
        )
    edges_str = ", ".join(f"`{u} -> {v}` ({w:.2f})" for u, v, w in result_dict["causal"]["edges"])
    lines.append(f"- **Inferred Edges:** {edges_str or 'None'}")

    lines.extend(["", "## 3. Model-Free Symmetries, Conservation Laws & Dynamical Regime (`W-LIND`)", ""])
    sym = result_dict["symmetry"]
    lines.append(
        f"- **Regime Classification:** `{sym['regime_class']}` (Divergence $\\nabla\\cdot f =$ `{sym['symbolic_divergence']}`, $\\hat{{\\lambda}}_1 =$ `{sym['max_lyapunov_est']:.3f}`)"
    )
    lines.append(f"- **Closed-Loop Search Space Pruned:** `{result_dict['pruning_ratio']*100:.1f}%`")
    lines.append(f"- **Discrete Symmetries:** `{sym['discrete_symmetries']}`")
    lines.append(f"- **Conserved Quantities / First Integrals:** `{sym['invariants']}`")
    lines.append(f"- **Continuous Lie Generators:** `{sym['lie_generators']}`")

    lines.extend(["", "## 4. Formal Verification & Derived Scientific Insights (`ASDS-Verify`)", ""])
    ver = result_dict["verification"]
    lines.append(f"- **Formal Proof Pass Rate:** `{ver['pass_rate']*100:.1f}%`")
    for ins in ver["derived_scientific_insights"]:
        lines.append(f"- {ins}")

    content = "\n".join(lines) + "\n"
    if output_path is None:
        return content
    p = Path(output_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(content, encoding="utf-8")
    return p


def export_latex_report(result_dict: dict[str, Any], output_path: str | Path | None = None) -> Path | str:
    """Generate a publication-ready LaTeX discovery summary snippet."""
    local_map = {v: sp.Symbol(v) for v in result_dict.get("var_names", [])}
    eq_lines = []
    for eq in result_dict["discovered_equations"]:
        try:
            tex = sp.latex(sp.sympify(eq["expr_str"], locals=local_map))
        except Exception:
            tex = eq["expr_str"]
        eq_lines.append(rf"  \frac{{d{eq['target_var']}}}{{dt}} &= {tex} \\")

    body = "\n".join(
        [
            r"% Auto-generated by ASDS-OMEGA v2.0 (VECSD)",
            rf"\section*{{Autonomous Discovery Certificate: \texttt{{{result_dict['dataset_name']}}}}}",
            r"\begin{align}",
            *eq_lines,
            r"\end{align}",
            rf"\noindent \textbf{{Overall Evidence Confidence:}} {result_dict['evidence']['overall_confidence']:.3f} \quad "
            rf"\textbf{{Mean Weak $R^2$:}} {result_dict['evidence']['mean_weak_r2']:.4f} \quad "
            rf"\textbf{{Search Space Pruned:}} {result_dict['pruning_ratio']*100:.1f}\%.",
        ]
    ) + "\n"
    if output_path is None:
        return body
    p = Path(output_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(body, encoding="utf-8")
    return p
